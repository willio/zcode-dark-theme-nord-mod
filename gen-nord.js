// Parse .dark/.theme-zai-dark rules from ZCode's bundle CSS and emit Nord overrides.
// Dark literal colors (by luminance band) map to Nord Polar Night, alpha preserved.
// Single-pass tokenizer: replaced output is never re-scanned.
const fs = require('fs');

const cssPath = process.argv[2];
const outPath = process.argv[3];
const css = fs.readFileSync(cssPath, 'utf8');

const NORD = [
  [0x2e, 0x34, 0x40], // nord0 — base backgrounds
  [0x3b, 0x42, 0x52], // nord1 — panels / headers / tabs
  [0x43, 0x4c, 0x5e], // nord2 — cards / menus / popovers
  [0x4c, 0x56, 0x6a], // nord3 — hover / tags / terminal-black
];

function lum(r, g, b) {
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
}
function band(L) {
  // Calibrated to ZCode's dark ramp: #101010-#161616 base, #202020 panels,
  // #2b2b2b cards, #363636 hover/tags -> nord0..nord3 respectively.
  if (L <= 0.11) return 0;
  if (L <= 0.14) return 1;
  if (L <= 0.19) return 2;
  if (L <= 0.235) return 3;
  return -1; // not dark — leave as-is
}
function nordCss([r, g, b], a) {
  if (a === undefined || a >= 1) {
    return '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');
  }
  return `rgba(${r}, ${g}, ${b}, ${Math.round(a * 1000) / 1000})`;
}
function hslToRgb(h, s, l) {
  s /= 100; l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
}

function parseColor(tok) {
  if (tok[0] === '#') {
    let h = tok.slice(1);
    let a = 1;
    if (h.length === 3 || h.length === 4) {
      if (h.length === 4) { a = parseInt(h[3] + h[3], 16) / 255; h = h.slice(0, 3); }
      h = h.split('').map((c) => c + c).join('');
    } else if (h.length === 8) {
      a = parseInt(h.slice(6), 16) / 255;
      h = h.slice(0, 6);
    }
    if (h.length !== 6 || /[^0-9a-fA-F]/.test(h)) return null;
    return { rgb: [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)), alpha: a };
  }
  const nums = tok.match(/-?[\d.]+%?/g) || [];
  if (nums.length < 3) return null;
  const pn = (x) => (x.endsWith('%') ? parseFloat(x) / 100 : parseFloat(x));
  if (tok.startsWith('hsl')) {
    return { rgb: hslToRgb(parseFloat(nums[0]), pn(nums[1]) * 100, pn(nums[2]) * 100), alpha: nums[3] === undefined ? 1 : pn(nums[3]) };
  }
  const conv = (x) => (x.endsWith('%') ? Math.round((parseFloat(x) / 100) * 255) : parseFloat(x));
  return {
    rgb: [nums[0], nums[1], nums[2]].map(conv),
    alpha: nums[3] === undefined ? 1 : pn(nums[3]),
  };
}

// longest-first alternation so 6/8-digit hex isn't eaten by the 3/4-digit rule
const tokenRe = /#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g;

function remapValue(value) {
  let changed = false;
  const out = value.replace(tokenRe, (tok) => {
    const c = parseColor(tok);
    if (!c || c.rgb.some((v) => isNaN(v))) return tok;
    const b = band(lum(c.rgb[0], c.rgb[1], c.rgb[2]));
    if (b < 0) return tok;
    changed = true;
    return nordCss(NORD[b], c.alpha);
  });
  return { value: out, changed };
}

// Collect rules whose selector targets the dark theme.
const rules = [];
const ruleRe = /([^{}]+)\{([^{}]*)\}/g;
let m;
while ((m = ruleRe.exec(css))) {
  const sel = m[1].trim();
  if (/(^|[\s,>+~])\.dark([\s,>+~:.[]|$)/.test(sel) || /(^|[\s,>+~])\.theme-zai-dark([\s,>+~:.[]|$)/.test(sel)) {
    rules.push({ sel, body: m[2] });
  }
}

let emitted = 0;
const out = [];
out.push(`/* ZCODE-NORD-MOD-START ==== dark backgrounds -> Nord Polar Night ====
   Generated by gen-nord.js from the original .dark/.theme-zai-dark rules.
   Re-run apply.sh after a ZCode app update.
ZCODE-NORD-MOD-HEADER-END */`);

for (const { sel, body } of rules) {
  const declRe = /(--[\w-]+)\s*:\s*([^;]+);/g;
  const mapped = [];
  let d;
  while ((d = declRe.exec(body))) {
    const r = remapValue(d[2].trim());
    if (r.changed) mapped.push(`  ${d[1]}: ${r.value} !important;`);
  }
  if (mapped.length) {
    out.push(`${sel}{\n${mapped.join('\n')}\n}`);
    emitted += mapped.length;
  }
}

// Monaco code blocks (chat) — vs-dark background #1e1e1e is outside the var system.
out.push(`.theme-zai-dark .monaco-editor,
.theme-zai-dark .monaco-editor .margin,
.theme-zai-dark .monaco-editor .monaco-editor-scrollable-element > .monaco-editor-background {
  --vscode-editor-background: #2E3440 !important;
  --vscode-editorGutter-background: #2E3440 !important;
  background-color: #2E3440 !important;
}`);

fs.writeFileSync(outPath, out.join('\n') + '\n/* ZCODE-NORD-MOD-END */\n');
console.log(`rules scanned: ${rules.length}`);
console.log(`declarations overridden: ${emitted}`);
console.log(`output bytes: ${fs.statSync(outPath).size}`);
